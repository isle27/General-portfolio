const { chromium } = require('../Ai-portfolio/node_modules/playwright');
const assert = require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
 const page=await browser.newPage({viewport:{width:1170,height:1280},deviceScaleFactor:1});
 await page.goto('http://127.0.0.1:3000/',{waitUntil:'domcontentloaded'});
 await page.waitForFunction(()=>[...document.querySelectorAll('img')].every(e=>e.complete));
 await page.screenshot({path:'portfolio-desktop.png',fullPage:true});
 assert.equal(await page.locator('.portrait img').evaluate(e=>getComputedStyle(e).mixBlendMode),'normal');
 assert.equal(await page.locator('.portrait img').evaluate(e=>getComputedStyle(e).filter),'none');
 assert.equal(await page.locator('.portrait').evaluate(e=>getComputedStyle(e).clipPath),'none');
 const headerBottom=await page.locator('header').evaluate(e=>e.getBoundingClientRect().bottom);
 assert.ok(await page.locator('.portrait img').evaluate((e,bottom)=>e.getBoundingClientRect().top>=bottom,headerBottom));
 assert.equal(await page.locator('.portrait').evaluate(e=>getComputedStyle(e,'::before').animationName),'portrait-swell');
 assert.equal(await page.locator('.technology img').count(),13);
 assert.equal(await page.locator('.expertise-grid li').count(),12);
 assert.ok(await page.locator('.technology img').evaluateAll(es=>es.every(e=>e.complete&&e.naturalWidth>0&&e.getBoundingClientRect().width<=23)));
 await page.getByRole('button',{name:'Software Engineer'}).click();
 assert.equal(await page.locator('.project-card').count(),3);
 await page.locator('#back').click();
 assert.equal(await page.locator('#about-content').isVisible(),true);
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'portfolio-mobile.png',fullPage:true});
 const overflow=await page.evaluate(()=>({width:document.documentElement.scrollWidth,viewport:innerWidth,elements:[...document.querySelectorAll('body *')].filter(e=>e.getBoundingClientRect().right>innerWidth+1&&getComputedStyle(e).position!=='absolute').map(e=>({tag:e.tagName,class:e.className,right:e.getBoundingClientRect().right})).slice(0,10)}));
 assert.ok(overflow.width<=overflow.viewport,JSON.stringify(overflow));
 await page.setViewportSize({width:1536,height:900});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 const navVisible=await page.locator('header a, header button').evaluateAll(es=>es.every(e=>{const r=e.getBoundingClientRect();return r.left>=0&&r.right<=innerWidth&&r.top>=0}));
 assert.ok(navVisible);
 await page.emulateMedia({reducedMotion:'reduce'});
 assert.equal(await page.locator('.wave-front').first().evaluate(e=>getComputedStyle(e).animationName),'none');
 console.log('Passed: untinted portrait, 13 small loaded icons, 12 AI skills, project switching, mobile overflow, reduced motion');
 await browser.close();
})().catch(e=>{console.error(e);process.exitCode=1});
